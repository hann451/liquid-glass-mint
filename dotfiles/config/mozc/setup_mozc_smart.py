def encode_varint(n):
    out = bytearray()
    n = int(n)
    while True:
        b = n & 0x7F
        n >>= 7
        if n:
            out.append(b | 0x80)
        else:
            out.append(b)
            break
    return bytes(out)


def field_varint(tag, val):
    return encode_varint((tag << 3) | 0) + encode_varint(val)


def field_bytes(tag, data):
    if isinstance(data, str):
        data = data.encode("utf-8")
    return encode_varint((tag << 3) | 2) + encode_varint(len(data)) + data


