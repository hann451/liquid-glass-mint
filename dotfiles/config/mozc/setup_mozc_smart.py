def build_user_dictionary_db():
    encoded_entries = bytearray()
    valid_count = 0
    for key, val, pos in ENTRIES:
        if not HIRAGANA_RE.match(key):
            raise ValueError(f"Invalid hiragana reading key: {key}")
        entry_bytes = (
            field_bytes(1, key)
            + field_bytes(2, val)
            + field_varint(5, pos)
        )
        encoded_entries += field_bytes(4, entry_bytes)
        valid_count += 1

    dict_bytes = (
        field_varint(1, 10001)
        + field_bytes(3, "英単語・Webスマート辞書")
        + bytes(encoded_entries)
    )
    storage_bytes = field_varint(1, 0) + field_bytes(2, dict_bytes)
    return storage_bytes, valid_count


def main():
    os.makedirs(MOZC_DIR, exist_ok=True)
    cfg_bytes = build_config1_db()
    with open(os.path.join(MOZC_DIR, "config1.db"), "wb") as f:
        f.write(cfg_bytes)

    ud_bytes, cnt = build_user_dictionary_db()
    with open(os.path.join(MOZC_DIR, "user_dictionary.db"), "wb") as f:
        f.write(ud_bytes)

    print(f"MOZC_OK entries={cnt} config1={len(cfg_bytes)}B user_dict={len(ud_bytes)}B")


if __name__ == "__main__":
    main()
